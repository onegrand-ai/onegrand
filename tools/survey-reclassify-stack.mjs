#!/usr/bin/env node
// survey-reclassify-stack.mjs — re-derive each storefront's platform from HARD
// evidence only, and record the evidence.
//
// WHY. The survey's first-pass platform detection matched bare product names in
// page text: a site that merely mentions "Magento" scored as running Magento, and
// seven storefronts came back attributed to three or four platforms at once, which
// no site does. That is the same error the probe's challenge detector already
// guards against — this project once flagged its OWN site as protected by DataDome
// because its log entries discuss DataDome. Prose is not evidence. It was not
// caught there because platform names looked like fingerprints rather than words.
//
// It matters because "UCP adoption by stack" is the survey's headline table. An
// attribution built from prose would put bespoke storefronts into named-platform
// rows and move the number the whole argument rests on.
//
// WHAT COUNTS AS HARD EVIDENCE. An asset URL, a cookie or JS global, a response
// header, or a framework-specific path — things a page emits because the software
// is actually running, not because someone wrote about it. Every match is stored
// verbatim, so any attribution in the published table can be challenged by looking
// at the string that produced it.
//
// COST. One GET per storefront, on hosts whose robots.txt was already fetched and
// already permitted "/" in the measurement pass. No host is asked anything new.
//
// --ucp (added 2026-08-12, cycle 94): restrict to storefronts that serve a UCP
// profile, and include the profile's own bytes in the evidence haystack. The
// homepage is not the only thing a site emits: dkhoonemirates.com's homepage
// carries no platform fingerprint, but its UCP profile serves its logo and
// payment icons from media.zid.store — the profile is generated by Zid, and
// reading only "/" filed a platform merchant under bespoke. Same lesson as the
// 400 KB truncation: what the instrument declines to read arrives in the output
// looking like a fact about the world.
//
// Usage: node tools/survey-reclassify-stack.mjs [--state path] [--concurrency 16] [--ucp]

import fs from 'node:fs';
import { probe } from './agent-passability.mjs';

const argv = process.argv.slice(2);
const statePath = argv.includes('--state') ? argv[argv.indexOf('--state') + 1] : '.scratch/survey-state.json';
const CONC = argv.includes('--concurrency') ? Number(argv[argv.indexOf('--concurrency') + 1]) : 16;

// Each entry: [name, regex]. Every regex requires a URL, a path, a header, a
// cookie or a JS global — never a bare word in running text.
const HARD = [
  ['shopify', /cdn\.shopify\.com|\.myshopify\.com|x-shopify-|Shopify\.theme|shopify-features/i],
  ['woocommerce', /wp-content\/plugins\/woocommerce|woocommerce-page|wc-ajax=|class=["'][^"']*woocommerce-/i],
  ['magento', /\/pub\/static\/|\/static\/version\d+\/frontend\/|mage\/cookies|Magento_[A-Z]|data-mage-init/i],
  ['bigcommerce', /cdn\d*\.bigcommerce\.com|bigcommerce\.com\/s-/i],
  ['salesforce-commerce', /demandware\.static|\/on\/demandware\.store|demandware\.edgesuite/i],
  ['prestashop', /\/modules\/ps_|var\s+prestashop|prestashop\.js|id_product_attribute/i],
  ['shopware', /\/bundles\/storefront|window\.shopware|shopware\.min\.js|\/bundles\/shopware/i],
  ['vtex', /vtexassets\.com|vtexcommercestable|vtex\.com\/_v\//i],
  ['wix-stores', /static\.wixstatic\.com.{0,200}stores|wix-stores/i],
  ['squarespace-commerce', /static1\.squarespace\.com|sqs-commerce|squarespace\.com\/universal/i],
  ['commercetools', /commercetools\.com\/|ctp-|\.commercetools\./i],
  ['saleor', /saleor\.cloud|saleor-api|\/graphql\/.{0,40}saleor/i],
  ['centra', /centracdn\.net|centra\.com\/api/i],
  ['ecwid', /app\.ecwid\.com|ecwid\.com\/script/i],
  ['opencart', /catalog\/view\/theme|index\.php\?route=common/i],
  ['shoplazza', /shoplazza\.com/i],
  ['salla', /salla\.sa|cdn\.salla\.network/i],
  // Asset/CDN URLs only — "zid" is also an ordinary word and a common name.
  ['zid', /media\.zid\.store|cdn\.zid\.store|\.zid\.store\//i],
];

const UCP_ONLY = argv.includes('--ucp');

const state = JSON.parse(fs.readFileSync(statePath, 'utf8'));
let shops = state.rows.filter((r) => r.outcome === 'storefront');
if (UCP_ONLY) shops = shops.filter((r) => r.paths?.['/.well-known/ucp']?.present);
console.error(`re-deriving stack for ${shops.length} storefronts from hard evidence only${UCP_ONLY ? ' (UCP-serving rows, profile bytes included)' : ''}`);

let i = 0, done = 0;
async function worker() {
  while (i < shops.length) {
    const row = shops[i++];
    const r = await probe(`https://${row.domain}/`);
    const body = r.body || '';
    let profileBody = '';
    if (UCP_ONLY) {
      const p = await probe(`https://${row.domain}/.well-known/ucp`);
      if (p.status === 200) profileBody = p.body || '';
    }
    const hay = body + ' ' + profileBody + ' ' + (r.platform || '') + ' ' + (r.server || '');
    const hits = [];
    for (const [name, rx] of HARD) {
      const m = hay.match(rx);
      if (m) hits.push({ platform: name, evidence: String(m[0]).slice(0, 80) });
    }
    row.stackStrict = {
      platforms: hits.map((h) => h.platform),
      evidence: hits,
      refetchStatus: r.status,
      at: new Date().toISOString(),
    };
    done++;
    if (done % 20 === 0) { fs.writeFileSync(statePath, JSON.stringify(state, null, 1)); console.error(`  ${done}/${shops.length}`); }
  }
}
await Promise.all(Array.from({ length: CONC }, worker));

state.stackReclassifiedAt = new Date().toISOString();
fs.writeFileSync(statePath, JSON.stringify(state, null, 1));

const counts = {};
let multi = 0, none = 0;
for (const r of shops) {
  const p = r.stackStrict?.platforms || [];
  if (p.length > 1) multi++;
  if (p.length === 0) none++;
  const k = p.join('+') || 'bespoke/unidentified';
  counts[k] = (counts[k] || 0) + 1;
}
console.error(`\nstrict attribution: ${JSON.stringify(counts, null, 1)}`);
console.error(`multi-platform ${multi}, unidentified ${none}`);
